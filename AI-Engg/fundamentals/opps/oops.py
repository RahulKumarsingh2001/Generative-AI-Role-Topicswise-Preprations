# What is OOP?
# OOP stands for Object-Oriented Programming.

# Python is an object-oriented language, allowing you to structure your code using classes
# and objects for better organization and reusability.




# Class: A blueprint used to create objects. (Blueprint containing attributes and methods)
# Object: An instance created from a class.


# create a class
class MyClass:
  x = 5
  
  
# Create Object
p1 = MyClass()
print(p1.x)  


# Delete Objects
del p1

# Multiple Objects
p1 = MyClass()
p2 = MyClass()
p3 = MyClass()

print(p1.x)
print(p2.x)
print(p3.x)



