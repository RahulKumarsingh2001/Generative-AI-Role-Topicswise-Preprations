# why datasets?
# A dataset is a collection of related observations or data points 
# used for analysis, processing, retrieval, training, or evaluation.


# Types of datasets:
# Structured: SQL tables, CSV, spreadsheets.
# Semi-structured: JSON, JSONL, XML, nested API responses.
# Unstructured: Text documents, PDFs, images, audio, video.
# Numerical: Integer and floating-point values.
# Categorical: Department, product category, sentiment.
# Ordinal: Ratings such as low, medium, high.
# Temporal: Dates, timestamps, event sequences.
# Multimodal: Data combining text, images, audio, or video.





# Dataset characteristics
# Understand the following:
# - Number of rows and columns.
# - Data types and schema.
# - Dataset size in bytes or tokens.
# - Cardinality: number of unique values.
# - Class distribution and imbalance.
# - Completeness: how much data is missing.
# - Accuracy and consistency.
# - Data provenance: where the data originated.
# - Data freshness and update frequency.
# - Representativeness: whether the data reflects the intended use case.




# Dataset design concepts
# - One row per entity versus one row per event.
# - Unique identifiers and primary keys.
# - Relationships between datasets.
# - One-to-one, one-to-many and many-to-many relationships.
# - Nested records and arrays.
# - Denormalized versus normalized data.
# - Immutable raw data versus transformed datasets.
# - Data contracts: agreements about schema and expected behavior.